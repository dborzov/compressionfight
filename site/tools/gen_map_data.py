#!/usr/bin/env python3
"""Generate site/data/map.yaml (sidebar + prev/next order) from docs/map/map.md."""
import re, sys, json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "docs/map/map.md").read_text()
sections, cur, seen = [], None, set()
for line in src.splitlines():
    m = re.match(r"## (.+)", line)
    if m:
        head = m.group(1).strip()
        name, _, sub = head.partition(":")
        sub = re.sub(r"\s*\(.*\)\s*$", "", sub).strip()
        cur = {"name": name.strip(), "sub": sub, "items": []}
        sections.append(cur); continue
    if cur is None or not line.startswith("- "):
        continue
    link = re.search(r"\[([^\]]*)\]\(zoo/([\w-]+)\.md\)", line)
    if not link or link.group(2) in seen:
        continue
    slug = link.group(2)
    bold = re.match(r"- \*\*(.+?)\*\*", line)
    if bold and link.group(1) != "article":
        continue  # cross-reference, not the family's own article
    if bold:
        title = bold.group(1)
    else:
        title = link.group(1)
    # "Modeling and coding: bits are surprise" -> keep full; for bold families keep family name
    cur["items"].append({"slug": slug, "title": title})
    seen.add(slug)
sections = [s for s in sections if s["items"]]
out = ["# GENERATED by site/tools/gen_map_data.py from docs/map/map.md. Do not edit.", "sections:"]
for s in sections:
    out.append(f"  - name: {json.dumps(s['name'])}")
    out.append(f"    sub: {json.dumps(s['sub'])}")
    out.append("    items:")
    for i in s["items"]:
        out.append(f"      - slug: {i['slug']}")
        out.append(f"        title: {json.dumps(i['title'], ensure_ascii=False)}")
(root / "site/data/map.yaml").write_text("\n".join(out) + "\n")
print(f"map.yaml: {len(sections)} sections, {len(seen)} articles", file=sys.stderr)
